import { EntitySchema } from "typeorm";

export const AcademicYear = new EntitySchema({
    name:"AcademicYear",
    tableName:"academic_years",
    columns:{
        academic_year_id:{
            type:"uuid",
            primary:true,
            generated:"uuid"
        },
        college_id:{
            type:"uuid",
            nullable:false
        },
        year:{
            type:"varchar",
            length:20,
            nullable:false
        },
        start_date:{
            type:"date",
            nullable:false
        },
        end_date:{
            type:"date",
            nullable:false
        },
        is_running:{
            type:"boolean",
            default:true,
            nullable:false
        },
        created_at:{
            type:"timestamp with time zone",
            createDate:true
        },
        updated_at:{
            type:"timestamp with time zone",
            updateDate:true
        }
    },
    relations:{
        college:{
            type:"many-to-one",
            target:"College",
            inverseSide:"accademicyears",
            joinColumn:{name:"college_id"}
        },
        academiccalendars:{
            type:"one-to-many",
            target:"AcademicCalendar",
            inverseSide:"academicyear"
        },
        studentEnrollments:{
            type:"one-to-many",
            target:"StudentEnrollment",
            inverseSide:"academicYear"
        },
         facultySubjectMappings:{
            type:"one-to-many",
            target:"FacultySubjectMapping",
            inverseSide:"academicYear"
        },
        assignments:{
            type:"one-to-many",
            target:"Assignment",
            inverseSide:"academicYear"
        },
         studyMaterials:{
            type:"one-to-many",
            target:"StudyMaterial",
            inverseSide:"academicYear"
        },
         attandanceSessions:{
            type:"one-to-many",
            target:"AttandanceSession",
            inverseSide:"academicYear"
        }

    },
    uniques:[
        {
            name:"UQ_academic_year_college",
            columns:["college","year"]
        }
    ]
})