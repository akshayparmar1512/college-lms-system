import { EntitySchema } from "typeorm";

export const StudyMaterial = new EntitySchema({
    name:"StudyMaterial",
    tableName:"study_material",
    columns:{
        material_id:{
            primary:true,
            type:"uuid",
            generated:"uuid"
        },
        college_id:{
            type:"uuid"
        },
        academic_year_id:{
            type:"uuid"
        },
        subject_id:{
            type:"uuid"
        },
        faculty_id:{
            type:"uuid"
        },
        curriculum_id:{
            type:"uuid"
        },
        file_url:{
            type:"varchar",
            length:255,
        },
        title:{
            type:"varchar",
            length:150,
            nullable:true
        },
        description:{
            type:"text",
            nullable:true
        },
        created_at:{
            type:"timestamp with time zone",
            createDate:true
        },
        updated_at:{
            type:"timestamp with time zone",
            updateDate:true
        }
    },
    relations:{
        college:{
            type:"many-to-one",
            target:"College",
            inverseSide:"studyMaterials",
            joinColumn:{name:"college_id"}
        },
        academicYear:{
            type:"many-to-one",
            target:"AcademicYear",
            inverseSide:"studyMaterials",
            joinColumn:{name:"academic_year_id"}
        },
        subject:{
            type:"many-to-one",
            target:"Subject",
            inverseSide:"studyMaterials",
            joinColumn:{name:"subject_id"}
        },
        faculty:{
            type:"many-to-one",
            target:"FacultyProfile",
            inverseSide:"studyMaterials",
            joinColumn:{name:"faculty_id"}
        },
        curriculum:{
            type:"many-to-one",
            target:"Curriculum",
            inverseSide:"studyMaterials",
            joinColumn:{name:"curriculum_id"}
        }
    }
})