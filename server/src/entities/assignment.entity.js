import { EntitySchema } from "typeorm";

export const Assignment = new EntitySchema({
    name:"Assignment",
    tableName:"assignments",
    columns:{
        assignment_id:{
            primary:true,
            type:"uuid",
            generated:"uuid"
        },
        college_id:{
            type:"uuid"
        },
        academic_year_id:{
            type:"uuid"
        },
        curriculum_id:{
            type:"uuid"
        },
        faculty_id:{
            type:"uuid"
        },
        subject_id:{
            type:"uuid"
        },
        title:{
            type:"varchar",
            length:150,
            nullable:true
        },
        description:{
            type:"text",
            nullable:true
        },
        file_url:{
            type:"varchar",
            length:255,
            nullable:false
        },
        due_date:{
            type:"date",
            nullable:false
        },
        divison:{
            type:"varchar",
            length:15,
            nullable:true
        },
        created_at:{
            type:"timestamp with time zone",
            createDate:true
        },
        updated_at:{
            type:"timestamp with time zone",
            updateDate:true
        }
    },
    relations:{
        college:{
            type:"many-to-one",
            target:"College",
            inverseSide:"assignments",
            joinColumn:{name:"college_id"}
        },
        academicYear:{
            type:"many-to-one",
            target:"AcademicYear",
            inverseSide:"assignments",
            joinColumn:{name:"academic_year_id"}
        },
        curriculum:{
            type:"many-to-one",
            target:"Curriculum",
            inverseSide:"assignments",
            joinColumn:{name:"curriculum_id"}
        },
        faculty:{
            type:"many-to-one",
            target:"FacultyProfile",
            inverseSide:"assignments",
            joinColumn:{name:"faculty_id"}
        },
        subject:{
            type:"many-to-one",
            target:"Subject",
            inverseSide:"assignments",
            joinColumn:{name:"subject_id"}
        },
        assignmentSubmissions:{
            type:"one-to-many",
            target:"AssignmentSubmission",
            inverseSide:"assignment"
        }
    }
})