import { EntitySchema } from "typeorm";

export const AttandanceSession = new EntitySchema({
    name:"AttandanceSession",
    tableName:"attandance_sessions",
    columns:{
        session_id:{
            primary:true,
            type:"uuid",
            generated:"uuid"
        },
        college_id:{
            type:"uuid"
        },
        academic_year_id:{
            type:"uuid"
        },
        curriculum_id:{
            type:"uuid"
        },
        subject_id:{
            type:"uuid"
        },
        faculty_id:{
            type:"uuid"
        },
        divison:{
            type:"varchar",
            length:20,
            nullable:true
        },
        batch:{
            type:"varchar",
            length:20,
            nullable:true
        },
        lecture_date:{
            type:"date"
        },
        lecture_type:{
            type:"enum",
            enum:["lecture","lab"]
        },
        created_at:{
            type:"timestamp with time zone",
            createDate:true
        },
        updated_at:{
            type:"timestamp with time zone",
            updateDate:true
        }
    },
    relations:{
        college:{
            type:"many-to-one",
            target:"College",
            inverseSide:"attandanceSessions",
            joinColumn:{name:"college_id"}
        },
        academicYear:{
            type:"many-to-one",
            target:"AcademicYear",
            inverseSide:"attandanceSessions",
            joinColumn:{name:"academic_year_id"}
        },
        curriculum:{
            type:"many-to-one",
            target:"Curriculum",
            inverseSide:"attandanceSessions",
            joinColumn:{name:"curriculum_id"}
        },
        subject:{
            type:"many-to-one",
            target:"Subject",
            inverseSide:"attandanceSessions",
            joinColumn:{name:"subject_id"}
        },
        faculty:{
            type:"many-to-one",
            target:"FacultyProfile",
            inverseSide:"attandanceSessions",
            joinColumn:{name:"faculty_id"}
        },
        studentAttendances:{
            type:"one-to-many",
            target:"StudentAttendance",
            inverseSide:"attendanceSession"
        }
    }
})